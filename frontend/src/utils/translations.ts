export function useTranslation(languageCode: string) {
  const t = (key: string) => {
    return TRANSLATIONS[languageCode]?.[key] || TRANSLATIONS['hi-IN']?.[key] || TRANSLATIONS['en-IN'][key] || key;
  };
  return { t };
}

// Fallback logic for TTS voices since some regional dialects (like Bhojpuri) don't have native TTS support in browsers yet
export function getTTSLang(languageCode: string): string {
  if (languageCode === 'bho-IN') return 'hi-IN'; // Bhojpuri uses Hindi voice perfectly
  if (languageCode === 'mai-IN') return 'hi-IN'; // Maithili uses Hindi voice
  if (languageCode === 'doi-IN') return 'hi-IN'; // Dogri uses Hindi voice
  if (languageCode === 'kok-IN') return 'mr-IN'; // Konkani uses Marathi voice
  // fallback for unsupported others could be added here
  return languageCode;
}
